export function createStorySparkles(host: HTMLElement) {
  const layer = document.createElement('div')
  layer.className = 'story-sparkles'
  layer.setAttribute('aria-hidden', 'true')
  host.append(layer)
  function show(id: string) {
    layer.replaceChildren()
    layer.dataset.panelId = id
    const key = id === 'cover' ? id : id.split('-')[0]!
    const quiet = /^(26|27|28|29|30|31)$/.test(key)
    layer.classList.toggle('quiet', quiet)
    const cool = [
      '03',
      '04',
      '20',
      '21',
      '22',
      '23',
      '32',
      '33',
      '34',
      '46',
      '47',
      '48',
      '49',
      '50',
      '60',
    ].includes(key)
    layer.style.setProperty('--sparkle-colour', cool ? '#e1faff' : '#fff1bf')
    const points = storySparkleSites[key] ?? []
    points.forEach(([x, y], i) => {
      const glint = document.createElement('span')
      glint.className = 'story-sparkle'
      glint.style.left = `${x}%`
      glint.style.top = `${y}%`
      glint.style.setProperty('--size', `${quiet ? 7 : 9 + (i % 3) * 3}px`)
      glint.style.setProperty(
        '--duration',
        `${(quiet ? 12 : 7) + (i % 4) * 1.3}s`
      )
      glint.style.setProperty('--delay', `${-(i * 2.17 + x * 0.07)}s`)
      layer.append(glint)
    })
    visibility()
  }
  function visibility() {
    layer.classList.toggle('paused', document.hidden)
  }
  document.addEventListener('visibilitychange', visibility)
  return {
    show,
    dispose() {
      layer.remove()
      document.removeEventListener('visibilitychange', visibility)
    },
  }
}
