import { chromium } from '@playwright/test'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
await page.goto('http://127.0.0.1:4173/tests/fixtures/story-reader.html')
await page.getByRole('button', {name: 'Read Sea friends'}).click()
await page.waitForFunction(() => document.querySelector('dialog')?.dataset.storyOpening === 'false')
const show = page.getByRole('button', {name: 'Show story controls'})
if (await show.isVisible()) await show.click()
const slider = page.getByRole('slider', {name: 'Story progress'})
console.log('max', await slider.getAttribute('max'))
await slider.fill('65')
await page.waitForTimeout(4000)
await page.locator('.dinosaur-flight-scene.ready.flying').waitFor()
console.log('initial', await page.locator('.dinosaur-flight-scene.ready.flying').getAttribute('data-panel-id'))
await page.screenshot({path: 'target/flight-before.png'})
await page.getByRole('dialog').focus()
await page.keyboard.press('ArrowRight')
const bridge = page.locator('.story-transition')
await bridge.waitFor()
await page.waitForFunction(() => document.querySelector('.story-transition')?.dataset.ready === 'true')
console.log('kind', await bridge.getAttribute('data-transition'))
await bridge.evaluate(el => el.getAnimations({subtree: true}).forEach(a => {a.pause(); a.currentTime=2799}))
const inspect = el => [...el.querySelectorAll('[data-rider="diana"], [data-rider="diana"] img')].map(e => {const s=getComputedStyle(e); return {cls:e.className,box:JSON.stringify(e.getBoundingClientRect()),style:e.getAttribute('style'),left:s.left,bottom:s.bottom,width:s.width,height:s.height,transform:s.transform}})
console.log('bridge', await bridge.evaluate(inspect))
await page.screenshot({path:'target/flight-end-bridge.png'})
await bridge.evaluate(el=>el.getAnimations({subtree:true}).forEach(a=>a.finish()))
await bridge.waitFor({state:'detached'})
await page.locator('.dinosaur-flight-scene.ready.flying').evaluate(el=>el.getAnimations({subtree:true}).forEach(a=>{a.pause();a.currentTime=0}))
console.log('final', await page.locator('.dinosaur-flight-scene.ready.flying').evaluate(inspect))
await page.screenshot({path:'target/flight-end-final.png'})
await browser.close()
